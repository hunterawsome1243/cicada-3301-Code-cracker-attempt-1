#!/usr/bin/env python3
"""Freeze cicada_tools' own decode of every solved section as an independent reference.

Runs the vendored ``yo-yo-yo-jbo/cicada_tools`` transformer pipeline (its code, not
ours) and writes ``data/reference/cicada_tools_solved.json``. The regression suite
compares runeforge's decoders against this file, so it must never be produced by
runeforge itself.

Needs ``sympy`` (a cicada_tools dependency). Usage:

    python scripts/extract_reference.py           # (re)write the reference
    python scripts/extract_reference.py --check   # fail if the committed file is stale
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import warnings
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from runeforge.paths import REFERENCE_DIR  # noqa: E402
from runeforge.sources import CICADA_TOOLS_DIR, raw_path  # noqa: E402

OUT = REFERENCE_DIR / "cicada_tools_solved.json"


def extract() -> dict:
    ct_root = raw_path(CICADA_TOOLS_DIR)
    sys.path.insert(0, str(ct_root))
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", SyntaxWarning)
        from core import ProcessedText  # type: ignore[import-not-found]
        from liber_primus import LiberPrimus  # type: ignore[import-not-found]

    commit = subprocess.run(
        ["git", "-C", str(ct_root), "rev-parse", "HEAD"], capture_output=True, text=True, check=True
    ).stdout.strip()
    sections = []
    for d, sec in zip(
        sorted(p.name for p in (ct_root / "liber_primus").iterdir() if p.is_dir()),
        LiberPrimus.get_all_sections(),
        strict=True,
    ):
        if any(type(t).__name__ == "UnsolvedTransformer" for t in sec.transformers):
            continue
        spec = json.loads((ct_root / "liber_primus" / d / "section.json").read_text("utf-8"))
        pt = ProcessedText(section=sec)
        for t in sec.transformers:
            t.transform(pt)
        sections.append(
            {
                "dirname": d,
                "title": spec["title"],
                "transformers": spec["transformers"],
                "page_numbers": [p.get("number") for p in spec["pages"]],
                "cipher": "".join(pt._orig_runes),
                "plain": "".join(pt.get_runes()),
                "latin": pt.to_latin(),
            }
        )
    return {
        "$comment": "Generated by scripts/extract_reference.py by running cicada_tools' own "
        "pipeline. Do not hand-edit.",
        "source": {"repo": "yo-yo-yo-jbo/cicada_tools", "commit": commit},
        "sections": sections,
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="verify the committed file is current")
    args = ap.parse_args()
    text = json.dumps(extract(), ensure_ascii=False, indent=1) + "\n"
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"STALE: {OUT} does not match cicada_tools' current output", file=sys.stderr)
            return 1
        print(f"OK: {OUT} is current")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({len(json.loads(text)['sections'])} solved sections)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
